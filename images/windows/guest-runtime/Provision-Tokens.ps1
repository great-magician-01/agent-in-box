#Requires -RunAsAdministrator
<#
.SYNOPSIS
  Copies per-VM Guest Agent and Worker RPC tokens into the protected token dir.

.DESCRIPTION
  Tokens are generated by the host/control plane, never by the golden image.
  The source directory normally comes from a provisioning medium. This script
  validates the files, writes them atomically and restricts the destination ACL.
  Token values are never printed.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$SourceDirectory,
    [string]$TokenRoot = "C:\ProgramData\AgentInBox\tokens",
    [string]$User = $env:USERNAME,
    [switch]$RemoveSource
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

if (-not (Get-LocalUser -Name $User -ErrorAction SilentlyContinue)) {
    throw "Local user '$User' does not exist."
}
$userSid = (New-Object Security.Principal.NTAccount($User)).Translate(
    [Security.Principal.SecurityIdentifier]
).Value

New-Item -ItemType Directory -Force -Path $TokenRoot | Out-Null
& icacls.exe $TokenRoot /inheritance:r `
    "/grant:r" "*S-1-5-18:(OI)(CI)F" "*S-1-5-32-544:(OI)(CI)F" "*${userSid}:(OI)(CI)R" | Out-Null
if ($LASTEXITCODE -ne 0) { throw "Failed to restrict token directory ACL" }

foreach ($name in @("guest-agent.token", "worker-rpc.token")) {
    $source = Join-Path $SourceDirectory $name
    if (-not (Test-Path -LiteralPath $source -PathType Leaf)) {
        throw "Missing token file: $source"
    }
    $item = Get-Item -LiteralPath $source -Force
    if ($item.Attributes -band [IO.FileAttributes]::ReparsePoint) {
        throw "Refusing to read a token from a reparse point: $source"
    }
    if ($item.Length -lt 32 -or $item.Length -gt 4096) {
        throw "Token file has an invalid size: $source"
    }
    $value = (Get-Content -LiteralPath $source -Raw).Trim()
    if (-not $value -or $value -match "\s") {
        throw "Token file must contain one non-empty value without whitespace: $source"
    }
    $destination = Join-Path $TokenRoot $name
    $temporary = "$destination.tmp"
    Set-Content -LiteralPath $temporary -Value $value -NoNewline -Encoding ASCII
    Move-Item -LiteralPath $temporary -Destination $destination -Force
    & icacls.exe $destination /inheritance:r `
        "/grant:r" "*S-1-5-18:F" "*S-1-5-32-544:F" "*${userSid}:R" | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "Failed to restrict token ACL: $destination" }
    if ($RemoveSource) {
        Remove-Item -LiteralPath $source -Force
    }
    Write-Host "Provisioned $name (value not printed)."
}

Write-Host "Restart the AgentInBox-GuestAgent and AgentInBox-Worker tasks after rotating tokens."
